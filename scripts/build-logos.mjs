// Builds src/data/logos.generated.ts from simple-icons, keeping only the icons
// that src/data/platforms.ts asks for. Run it with `pnpm logos` after adding
// or changing an `icon` in platforms.ts. The test suite fails if you forget.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as simpleIcons from 'simple-icons';

// These are drawn by hand in src/data/logos.ts, so they are skipped here.
const DRAWN_BY_HAND = new Set(['linkedin', 'venmo']);

const root = fileURLToPath(new URL('..', import.meta.url));
const source = fs.readFileSync(`${root}src/data/platforms.ts`, 'utf8');
const wanted = [...new Set([...source.matchAll(/icon: '([^']+)'/g)].map((m) => m[1]))]
  .filter((slug) => !DRAWN_BY_HAND.has(slug))
  .sort();

const bySlug = new Map(
  Object.values(simpleIcons)
    .filter((icon) => icon && typeof icon === 'object' && 'slug' in icon)
    .map((icon) => [icon.slug, icon]),
);

const missing = [];
let body = '';
for (const slug of wanted) {
  const icon = bySlug.get(slug);
  if (!icon) {
    missing.push(slug);
    continue;
  }
  body += `  ${JSON.stringify(slug)}: { hex: '${icon.hex}', path: ${JSON.stringify(icon.path)} },\n`;
}

const out = `// Generated by scripts/build-logos.mjs from simple-icons. Do not edit by hand.
// Run \`pnpm logos\` after adding or changing an \`icon\` in platforms.ts.
export const GLYPHS: Record<string, { hex: string; path: string }> = {
${body}};
`;
fs.writeFileSync(`${root}src/data/logos.generated.ts`, out);
console.log(`Wrote ${wanted.length - missing.length} logos to src/data/logos.generated.ts`);
if (missing.length) {
  console.error(`simple-icons has no icon for: ${missing.join(', ')}. Use an image in public/logos/ instead.`);
  process.exitCode = 1;
}
